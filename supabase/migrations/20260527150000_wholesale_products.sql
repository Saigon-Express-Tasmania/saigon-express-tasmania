-- Wholesale catalogue items (public wholesale shop /wholesale-shop).

create table public.wholesale_products (
  id bigint primary key,
  name text not null,
  sku text,
  category text not null,
  description text,
  unit text not null,
  unit_price text not null,
  stock_qty integer not null,
  is_available boolean not null default true,
  min_order_qty integer not null default 1,
  image_urls jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.wholesale_products is
  'Wholesale products shown on the public /wholesale-shop catalogue.';

create index wholesale_products_is_available_category_idx
  on public.wholesale_products (is_available, category, id);

alter table public.wholesale_products enable row level security;

create policy "Anyone can read available wholesale products"
  on public.wholesale_products
  for select
  to anon, authenticated
  using (is_available = true);

grant select on public.wholesale_products to anon, authenticated;
grant insert, update, delete on public.wholesale_products to authenticated;
grant all on public.wholesale_products to service_role;

-- Admin CRUD
create policy "Admins can read all wholesale products"
  on public.wholesale_products
  for select
  to authenticated
  using (public.is_admin());

create policy "Admins can insert wholesale products"
  on public.wholesale_products
  for insert
  to authenticated
  with check (public.is_admin());

create policy "Admins can update wholesale products"
  on public.wholesale_products
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Admins can delete wholesale products"
  on public.wholesale_products
  for delete
  to authenticated
  using (public.is_admin());


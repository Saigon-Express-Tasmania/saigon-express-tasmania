-- Job application submissions (careers form: personal details, screening questions, review).

create type public.job_application_status as enum (
  'pending',
  'reviewing',
  'approved',
  'resolved',
  'rejected'
);

create table public.job_applications (
  id bigint generated by default as identity primary key,

  -- Posting context (from careers listing / apply flow)
  job_title text not null,
  job_location text,
  store_id bigint references public.store_locations (id) on delete set null,

  -- Step 1: Personal details
  legal_first_name text not null,
  legal_middle_names text,
  legal_last_name text not null,
  email text not null,
  phone text,
  resume_url text,
  resume_filename text,
  cover_letter_url text,
  cover_letter_filename text,
  agree_to_terms boolean not null default false,

  -- Step 2: Additional questions
  date_of_birth date,
  can_work_weekends text,
  commute_under_20_minutes text,
  work_availability text,

  -- Step 3: Review and submit
  candidate_message text,

  status public.job_application_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint job_applications_job_title_length check (
    char_length(trim(job_title)) between 1 and 256
  ),
  constraint job_applications_job_location_length check (
    job_location is null or char_length(trim(job_location)) between 1 and 256
  ),
  constraint job_applications_legal_first_name_length check (
    char_length(trim(legal_first_name)) between 1 and 128
  ),
  constraint job_applications_legal_middle_names_length check (
    legal_middle_names is null
    or char_length(trim(legal_middle_names)) between 1 and 128
  ),
  constraint job_applications_legal_last_name_length check (
    char_length(trim(legal_last_name)) between 1 and 128
  ),
  constraint job_applications_email_format check (
    email ~* '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$'
  ),
  constraint job_applications_phone_length check (
    phone is null or char_length(trim(phone)) between 1 and 32
  ),
  constraint job_applications_resume_url_length check (
    resume_url is null or char_length(trim(resume_url)) between 1 and 2048
  ),
  constraint job_applications_resume_filename_length check (
    resume_filename is null or char_length(trim(resume_filename)) between 1 and 256
  ),
  constraint job_applications_cover_letter_url_length check (
    cover_letter_url is null or char_length(trim(cover_letter_url)) between 1 and 2048
  ),
  constraint job_applications_cover_letter_filename_length check (
    cover_letter_filename is null
    or char_length(trim(cover_letter_filename)) between 1 and 256
  ),
  constraint job_applications_agree_to_terms_required check (agree_to_terms = true),
  constraint job_applications_dob_reasonable check (
    date_of_birth is null
    or (date_of_birth >= date '1900-01-01' and date_of_birth <= current_date)
  ),
  constraint job_applications_can_work_weekends_allowed check (
    can_work_weekends is null or can_work_weekends in ('Yes', 'No')
  ),
  constraint job_applications_commute_under_20_minutes_allowed check (
    commute_under_20_minutes is null
    or commute_under_20_minutes in ('Yes', 'No')
  ),
  constraint job_applications_work_availability_length check (
    work_availability is null
    or char_length(trim(work_availability)) between 1 and 2000
  ),
  constraint job_applications_candidate_message_length check (
    candidate_message is null
    or char_length(trim(candidate_message)) between 1 and 8000
  )
);


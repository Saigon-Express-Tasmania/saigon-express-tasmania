create or replace function public.submit_job_application(
  p_job_title text,
  p_legal_first_name text,
  p_legal_last_name text,
  p_email text,
  p_agree_to_terms boolean,
  p_job_location text default null,
  p_store_id bigint default null,
  p_legal_middle_names text default null,
  p_phone text default null,
  p_resume_url text default null,
  p_resume_filename text default null,
  p_cover_letter_url text default null,
  p_cover_letter_filename text default null,
  p_date_of_birth date default null,
  p_can_work_weekends text default null,
  p_commute_under_20_minutes text default null,
  p_work_availability text default null,
  p_candidate_message text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_job_title text := nullif(trim(p_job_title), '');
  v_job_location text := nullif(trim(p_job_location), '');
  v_legal_first_name text := nullif(trim(p_legal_first_name), '');
  v_legal_middle_names text := nullif(trim(p_legal_middle_names), '');
  v_legal_last_name text := nullif(trim(p_legal_last_name), '');
  v_email text := nullif(trim(p_email), '');
  v_phone text := nullif(trim(p_phone), '');
  v_resume_url text := nullif(trim(p_resume_url), '');
  v_resume_filename text := nullif(trim(p_resume_filename), '');
  v_cover_letter_url text := nullif(trim(p_cover_letter_url), '');
  v_cover_letter_filename text := nullif(trim(p_cover_letter_filename), '');
  v_can_work_weekends text := nullif(trim(p_can_work_weekends), '');
  v_commute_under_20_minutes text := nullif(trim(p_commute_under_20_minutes), '');
  v_work_availability text := nullif(trim(p_work_availability), '');
  v_candidate_message text := nullif(trim(p_candidate_message), '');
  v_id bigint;
begin
  if v_job_title is null
     or v_legal_first_name is null
     or v_legal_last_name is null
     or v_email is null
     or coalesce(p_agree_to_terms, false) is distinct from true then
    raise exception 'invalid request' using errcode = '22023';
  end if;

  if v_email !~* '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$' then
    raise exception 'invalid request' using errcode = '22023';
  end if;

  if v_can_work_weekends is not null
     and v_can_work_weekends not in ('Yes', 'No') then
    raise exception 'invalid request' using errcode = '22023';
  end if;

  if v_commute_under_20_minutes is not null
     and v_commute_under_20_minutes not in ('Yes', 'No') then
    raise exception 'invalid request' using errcode = '22023';
  end if;

  if p_date_of_birth is not null
     and (p_date_of_birth < date '1900-01-01' or p_date_of_birth > current_date) then
    raise exception 'invalid request' using errcode = '22023';
  end if;

  insert into public.job_applications (
    job_title,
    job_location,
    store_id,
    legal_first_name,
    legal_middle_names,
    legal_last_name,
    email,
    phone,
    resume_url,
    resume_filename,
    cover_letter_url,
    cover_letter_filename,
    agree_to_terms,
    date_of_birth,
    can_work_weekends,
    commute_under_20_minutes,
    work_availability,
    candidate_message
  )
  values (
    v_job_title,
    v_job_location,
    p_store_id,
    v_legal_first_name,
    v_legal_middle_names,
    v_legal_last_name,
    v_email,
    v_phone,
    v_resume_url,
    v_resume_filename,
    v_cover_letter_url,
    v_cover_letter_filename,
    true,
    p_date_of_birth,
    v_can_work_weekends,
    v_commute_under_20_minutes,
    v_work_availability,
    v_candidate_message
  )
  returning id into v_id;

  return jsonb_build_object(
    'id', v_id,
    'submitted', true
  );
end;
$$;


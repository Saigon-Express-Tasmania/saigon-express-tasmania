-- Franchise Resources Hub: global documents, announcements, and menu training
-- visible to all franchise-privileged members, plus per-member read/completion state.

-- ---------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------
create type public.franchise_resource_type as enum (
  'announcement',
  'document',
  'menu_training'
);

comment on type public.franchise_resource_type is
  'Kind of franchise portal resource shown in the Resources Hub.';

create type public.franchise_resource_taxonomy_place as enum (
  'announcement',
  'document',
  'academy'
);

comment on type public.franchise_resource_taxonomy_place is
  'Place of franchise resource taxonomy (announcement, document, or academy).';

create type public.franchise_resource_taxonomy_kind as enum (
  'folder',
  'category',
  'course',
  'period'
);

comment on type public.franchise_resource_taxonomy_kind is
  'Taxonomy dimension for franchise resources (category, course, or period).';

create type public.franchise_resource_member_status as enum (
  'not_seen',
  'seen',
  'completed'
);

comment on type public.franchise_resource_member_status is
  'Per-member engagement state for a franchise resource.';

-- ---------------------------------------------------------------------------
-- Taxonomy helper (category / course / period identities)
-- ---------------------------------------------------------------------------
create table public.franchise_resource_taxonomies (
  id bigint generated by default as identity primary key,
  place public.franchise_resource_taxonomy_place not null,
  kind public.franchise_resource_taxonomy_kind not null,
  alias text not null,
  label text not null,
  icon text,
  image_url text,
  description text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint franchise_resource_taxonomies_alias_format check (
    alias ~ '^[a-z0-9]+(?:[-_][a-z0-9]+)*$'
  ),
  constraint franchise_resource_taxonomies_label_length check (
    char_length(trim(label)) between 1 and 256
  ),
  constraint franchise_resource_taxonomies_sort_order_non_negative check (
    sort_order >= 0
  ),
  constraint franchise_resource_taxonomies_kind_alias_unique unique (kind, alias)
);

comment on table public.franchise_resource_taxonomies is
  'Lookup identities for franchise resource category, course, and period fields.';
comment on column public.franchise_resource_taxonomies.kind is
  'Which dimension this row describes: category, course, or period.';
comment on column public.franchise_resource_taxonomies.alias is
  'Stable machine key within a kind (lowercase kebab/snake).';
comment on column public.franchise_resource_taxonomies.label is
  'Human-readable label shown in filters and resource metadata.';

create index franchise_resource_taxonomies_kind_active_sort_idx
  on public.franchise_resource_taxonomies (kind, is_active, sort_order, label);

create trigger franchise_resource_taxonomies_set_updated_at
  before update on public.franchise_resource_taxonomies
  for each row
  execute function public.set_updated_at();


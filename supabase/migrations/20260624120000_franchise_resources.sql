  on public.franchise_resource_member_states (resource_id, status);

create trigger franchise_resource_member_states_set_updated_at
  before update on public.franchise_resource_member_states
  for each row
  execute function public.set_updated_at();

create or replace function public.sync_franchise_resource_member_state_timestamps()
returns trigger
language plpgsql
as $$
begin
  if new.status = 'seen'::public.franchise_resource_member_status then
    if new.first_seen_at is null then
      new.first_seen_at := coalesce(new.last_seen_at, now());
    end if;
    new.last_seen_at := coalesce(new.last_seen_at, now());
    new.completed_at := null;
    new.progress_percent := greatest(coalesce(new.progress_percent, 0), 1);
  elsif new.status = 'completed'::public.franchise_resource_member_status then
    new.first_seen_at := coalesce(new.first_seen_at, now());
    new.last_seen_at := coalesce(new.last_seen_at, now());
    new.completed_at := coalesce(new.completed_at, now());
    new.progress_percent := 100;
  else
    new.first_seen_at := null;
    new.last_seen_at := null;
    new.completed_at := null;
    new.acknowledged_at := null;
    new.progress_percent := 0;
  end if;

  return new;
end;
$$;

comment on function public.sync_franchise_resource_member_state_timestamps() is
  'Keeps first_seen_at, last_seen_at, completed_at, and progress aligned with status.';

create trigger franchise_resource_member_states_sync_timestamps
  before insert or update of status, first_seen_at, last_seen_at, completed_at, progress_percent
  on public.franchise_resource_member_states
  for each row
  execute function public.sync_franchise_resource_member_state_timestamps();

-- ---------------------------------------------------------------------------
-- Access helpers
-- ---------------------------------------------------------------------------
create or replace function public.can_access_franchise_resources()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select public.is_admin()
    or public.user_has_privilege('franchise'::public.business_type);
$$;

comment on function public.can_access_franchise_resources() is
  'True for admins and users with the franchise portal privilege.';

create or replace function public.franchise_resource_is_visible(
  resource public.franchise_resources
)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select resource.is_published
    and (resource.effective_from is null or resource.effective_from <= now())
    and (resource.effective_until is null or resource.effective_until > now());
$$;

comment on function public.franchise_resource_is_visible(public.franchise_resources) is
  'True when a franchise resource is currently published and within its effective window.';

grant execute on function public.can_access_franchise_resources()
  to authenticated, service_role;
grant execute on function public.franchise_resource_is_visible(public.franchise_resources)
  to authenticated, service_role;


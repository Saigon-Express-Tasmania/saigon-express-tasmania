create table public.franchise_resource_member_states (
  id bigint generated by default as identity primary key,
  resource_id bigint not null references public.franchise_resources (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  status public.franchise_resource_member_status not null default 'not_seen',
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  completed_at timestamptz,
  progress_percent smallint not null default 0,
  acknowledged_at timestamptz,
  is_favourite boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint franchise_resource_member_states_resource_user_unique
    unique (resource_id, user_id),
  constraint franchise_resource_member_states_progress_range check (
    progress_percent between 0 and 100
  ),
  constraint franchise_resource_member_states_seen_timestamps check (
    status = 'not_seen'::public.franchise_resource_member_status
    or first_seen_at is not null
  ),
  constraint franchise_resource_member_states_completed_timestamp check (
    status <> 'completed'::public.franchise_resource_member_status
    or completed_at is not null
  )
);


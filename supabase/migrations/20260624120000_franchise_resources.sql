  on public.franchise_resource_member_states
  for select
  to authenticated
  using (public.is_admin());

create policy "Franchise members can insert own resource states"
  on public.franchise_resource_member_states
  for insert
  to authenticated
  with check (
    public.can_access_franchise_resources()
    and user_id = auth.uid()
    and exists (
      select 1
      from public.franchise_resources as resource
      where resource.id = resource_id
        and public.franchise_resource_is_visible(resource)
    )
  );


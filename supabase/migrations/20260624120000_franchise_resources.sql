-- Ensure course_id and period_id taxonomy FK targets match the expected kind.
create or replace function public.enforce_franchise_resource_taxonomy_refs()
returns trigger
language plpgsql
as $$
declare
  v_kind public.franchise_resource_taxonomy_kind;
begin
  if new.course_id is not null then
    select kind into strict v_kind
    from public.franchise_resource_taxonomies
    where id = new.course_id;

    if v_kind <> 'course'::public.franchise_resource_taxonomy_kind then
      raise exception 'course_id must reference a taxonomy row with kind = course'
        using errcode = '23514';
    end if;
  end if;

  if new.period_id is not null then
    select kind into strict v_kind
    from public.franchise_resource_taxonomies
    where id = new.period_id;

    if v_kind <> 'period'::public.franchise_resource_taxonomy_kind then
      raise exception 'period_id must reference a taxonomy row with kind = period'
        using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

comment on function public.enforce_franchise_resource_taxonomy_refs() is
  'Validates course_id and period_id reference taxonomies of the matching kind.';

create trigger franchise_resources_enforce_taxonomy_refs
  before insert or update of course_id, period_id
  on public.franchise_resources
  for each row
  execute function public.enforce_franchise_resource_taxonomy_refs();


-- Ensure taxonomy FK targets match the expected kind.
create or replace function public.enforce_franchise_resource_taxonomy_refs()
returns trigger
language plpgsql
as $$
declare
  v_kind public.franchise_resource_taxonomy_kind;
begin
  if new.category_id is not null then
    select kind into strict v_kind
    from public.franchise_resource_taxonomies
    where id = new.category_id;

    if v_kind <> 'category'::public.franchise_resource_taxonomy_kind then
      raise exception 'category_id must reference a taxonomy row with kind = category'
        using errcode = '23514';
    end if;
  end if;

  if new.course_id is not null then
    select kind into strict v_kind
    from public.franchise_resource_taxonomies
    where id = new.course_id;

    if v_kind <> 'course'::public.franchise_resource_taxonomy_kind then
      raise exception 'course_id must reference a taxonomy row with kind = course'
        using errcode = '23514';
    end if;
  end if;

  if new.period_id is not null then
    select kind into strict v_kind
    from public.franchise_resource_taxonomies
    where id = new.period_id;

    if v_kind <> 'period'::public.franchise_resource_taxonomy_kind then
      raise exception 'period_id must reference a taxonomy row with kind = period'
        using errcode = '23514';
    end if;
  end if;

  return new;
end;
$$;

comment on function public.enforce_franchise_resource_taxonomy_refs() is
  'Validates category_id, course_id, and period_id reference taxonomies of the matching kind.';

create trigger franchise_resources_enforce_taxonomy_refs
  before insert or update of category_id, course_id, period_id
  on public.franchise_resources
  for each row
  execute function public.enforce_franchise_resource_taxonomy_refs();

-- ---------------------------------------------------------------------------
-- Per-member resource state (1 row per member per resource)
-- ---------------------------------------------------------------------------
create table public.franchise_resource_member_states (
  id bigint generated by default as identity primary key,
  resource_id bigint not null references public.franchise_resources (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  status public.franchise_resource_member_status not null default 'not_seen',
  first_seen_at timestamptz,
  last_seen_at timestamptz,
  completed_at timestamptz,
  progress_percent smallint not null default 0,
  acknowledged_at timestamptz,
  is_favourite boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint franchise_resource_member_states_resource_user_unique
    unique (resource_id, user_id),
  constraint franchise_resource_member_states_progress_range check (
    progress_percent between 0 and 100
  ),
  constraint franchise_resource_member_states_seen_timestamps check (
    status = 'not_seen'::public.franchise_resource_member_status
    or first_seen_at is not null
  ),
  constraint franchise_resource_member_states_completed_timestamp check (
    status <> 'completed'::public.franchise_resource_member_status
    or completed_at is not null
  )
);

comment on table public.franchise_resource_member_states is
  'Tracks each franchise member''s seen/completed status for a franchise resource.';
comment on column public.franchise_resource_member_states.first_seen_at is
  'When the member first opened the resource.';
comment on column public.franchise_resource_member_states.last_seen_at is
  'Most recent time the member opened the resource.';
comment on column public.franchise_resource_member_states.completed_at is
  'When the member marked the resource completed (or training finished).';
comment on column public.franchise_resource_member_states.progress_percent is
  'Optional progress for menu_training (0–100).';

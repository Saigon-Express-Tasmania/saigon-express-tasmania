-- Taxonomies: franchise members read active rows; admins manage all.
create policy "Franchise members can read active taxonomies"
  on public.franchise_resource_taxonomies
  for select
  to authenticated
  using (
    public.can_access_franchise_resources()
    and is_active = true
  );


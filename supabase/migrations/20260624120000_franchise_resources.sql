create or replace function public.can_access_franchise_resources()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select public.is_admin()
    or public.user_has_privilege('franchise'::public.business_type);
$$;

comment on function public.can_access_franchise_resources() is
  'True for admins and users with the franchise portal privilege.';

create or replace function public.franchise_resource_is_visible(
  resource public.franchise_resources
)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select resource.is_published
    and (resource.effective_from is null or resource.effective_from <= now())
    and (resource.effective_until is null or resource.effective_until > now());
$$;

comment on function public.franchise_resource_is_visible(public.franchise_resources) is
  'True when a franchise resource is currently published and within its effective window.';

grant execute on function public.can_access_franchise_resources()
  to authenticated, service_role;
grant execute on function public.franchise_resource_is_visible(public.franchise_resources)
  to authenticated, service_role;


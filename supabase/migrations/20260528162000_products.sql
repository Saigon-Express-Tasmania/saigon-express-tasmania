-- Unified product catalogue: alacarte menu, wholesale, and catering.

create type public.product_type as enum ('catering', 'wholesale', 'alacarte');

create type public.product_uom as enum ('CASE', 'EACH', 'LBS', 'KG');

grant usage on type public.product_type to anon, authenticated, service_role;
grant usage on type public.product_uom to anon, authenticated, service_role;

create table public.products (
  id bigint primary key,
  product_type public.product_type not null,

  name text not null,
  category text not null default '',
  description text not null default '',  
  is_available boolean not null default true,
  sort_order integer not null default 0,
  image_urls jsonb not null default '{}'::jsonb,

  -- Pricing (usage varies by product_type)
  price text not null default '',
  unit_price text not null default '',
  wholesale_price text,
  prices jsonb not null default '[]'::jsonb,

  -- Alacarte (menu)
  slug text not null default '',  
  related_items bigint[] not null default '{}'::bigint[],
  is_popular boolean not null default false,
  ingredients jsonb not null default '[]'::jsonb,
  energy integer not null default 0,
  food_content jsonb not null default '{}'::jsonb,
  spicy_level integer not null default 0,

  -- Wholesale
  sku text,
  unit text not null default '',
  daily_global_limit integer,
  daily_customer_limit integer,
  min_order_qty integer not null default 1,
  uom public.product_uom not null default 'EACH', -- Unit of Measure (e.g. CASE, EACH, LBS, KG).
  is_catch_weight boolean not null default false, -- TRUE if price adjusts based on final weight.

  -- Shipping (freight quoting per sellable unit)
  is_shippable boolean not null default false,
  ship_weight_kg numeric(10, 3),
  ship_length_cm numeric(10, 2),
  ship_width_cm numeric(10, 2),
  ship_height_cm numeric(10, 2),

  -- Catering
  serves text,
  includes jsonb not null default '[]'::jsonb,
  tag text not null default '',
  tag_bg text not null default '',
  note text,
  image_url text,

  constraint products_shippable_dims_check check (
    not is_shippable or (
      ship_weight_kg > 0
      and ship_length_cm > 0
      and ship_width_cm > 0
      and ship_height_cm > 0
    )
  ),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.products is
  'Unified product catalogue. Rows are distinguished by product_type: alacarte, wholesale, or catering.';
comment on column public.products.product_type is
  'Product channel: alacarte (menu), wholesale, or catering.';
comment on column public.products.price is
  'Display price for alacarte/catering (text, may include currency symbols).';
comment on column public.products.unit_price is
  'Numeric unit price for wholesale (stored as text).';
comment on column public.products.prices is
  'Tiered size/price options for catering hot dishes (json array).';
comment on column public.products.unit is
  'Wholesale pack description, e.g. bag 20 pcs.';
comment on column public.products.daily_global_limit is
  'Wholesale only: max units sold per Hobart calendar day across all customers.';
comment on column public.products.daily_customer_limit is
  'Wholesale only: max units one customer may buy per Hobart calendar day. Null = no cap.';
comment on column public.products.sku is
  'Stock-keeping unit. Seeds use AL-{id}, WH-{id}, or CT-{id} by product_type when not supplied.';
comment on column public.products.is_shippable is
  'When true, this SKU can be included in freight quotes. Requires ship_weight_kg and ship_*_cm.';
comment on column public.products.ship_weight_kg is
  'Dead weight per sellable unit (kg), e.g. one CASE or EACH.';
comment on column public.products.ship_length_cm is
  'Parcel length per sellable unit (cm).';
comment on column public.products.ship_width_cm is
  'Parcel width per sellable unit (cm).';
comment on column public.products.ship_height_cm is
  'Parcel height per sellable unit (cm).';

create index products_type_available_sort_idx
  on public.products (product_type, is_available, sort_order, id);

create index products_type_available_category_idx
  on public.products (product_type, is_available, category, id);

create index products_alacarte_slug_idx
  on public.products (slug)
  where product_type = 'alacarte'::public.product_type;

create index products_wholesale_shippable_idx
  on public.products (id)
  where product_type = 'wholesale'::public.product_type
    and is_shippable = true;

alter table public.products enable row level security;

create policy "Anyone can read available products"
  on public.products
  for select
  to anon, authenticated
  using (is_available = true);

create policy "Admins can read all products"
  on public.products
  for select
  to authenticated
  using (public.is_admin());

create policy "Admins can insert products"
  on public.products
  for insert
  to authenticated
  with check (public.is_admin());

create policy "Admins can update products"
  on public.products
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Admins can delete products"
  on public.products
  for delete
  to authenticated
  using (public.is_admin());

grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant all on public.products to service_role;


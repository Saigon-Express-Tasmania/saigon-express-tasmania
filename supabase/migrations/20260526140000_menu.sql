-- Public menu items (site menu pages and home best sellers).

create table public.menu (
  id bigint primary key,
  slug text not null default '',
  name text not null,
  description text,
  price text not null,
  wholesale_price text,
  category text not null,
  image_urls jsonb not null default '{}'::jsonb,
  related_items bigint[] not null default '{}'::bigint[],
  is_available boolean not null default true,
  is_popular boolean not null default false,
  sort_order integer not null default 0,
  ingredients jsonb not null default '[]'::jsonb
);

comment on table public.menu is
  'Menu items shown on the public site (menu page, home best sellers, etc.).';

create index menu_is_available_sort_order_idx
  on public.menu (is_available, sort_order, id);

create index menu_category_sort_order_idx
  on public.menu (category, sort_order, id);

create index menu_slug_idx
  on public.menu (slug);

alter table public.menu enable row level security;

create policy "Anyone can read available menu items"
  on public.menu
  for select
  to anon, authenticated
  using (is_available = true);

grant select on public.menu to anon, authenticated;
grant insert, update, delete on public.menu to authenticated;
grant all on public.menu to service_role;

-- Admin CRUD
create policy "Admins can read all menu items"
  on public.menu
  for select
  to authenticated
  using (public.is_admin());

create policy "Admins can insert menu items"
  on public.menu
  for insert
  to authenticated
  with check (public.is_admin());

create policy "Admins can update menu items"
  on public.menu
  for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Admins can delete menu items"
  on public.menu
  for delete
  to authenticated
  using (public.is_admin());


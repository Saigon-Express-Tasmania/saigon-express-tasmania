#!/usr/bin/env node
/**
 * Extracts featured reviews from refs/samples/reviews.json (tRPC batch index 0)
 * and updates the seed block in supabase/migrations/20260526120000_featured_reviews.sql
 *
 * Usage: node scripts/generate-featured-reviews-seed.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const batchPath = path.join(root, "refs/samples/reviews.json");
const extractedPath = path.join(root, "refs/samples/featured-reviews.json");
const menuExtractedPath = path.join(root, "refs/samples/menu.json");
const migrationPath = path.join(
  root,
  "supabase/migrations/20260526120000_featured_reviews.sql",
);

const BEGIN = "-- BEGIN featured_reviews seed (generated by scripts/generate-featured-reviews-seed.mjs)";
const END = "-- END featured_reviews seed";

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function loadReviews() {
  const batch = JSON.parse(fs.readFileSync(batchPath, "utf8"));
  if (!Array.isArray(batch) || batch.length === 0) {
    throw new Error("reviews.json: expected a non-empty tRPC batch array");
  }

  const reviews = batch[0]?.result?.data?.json;
  if (!Array.isArray(reviews)) {
    throw new Error("reviews.json: batch[0] has no featured reviews array");
  }

  return reviews;
}

function reviewToSqlRow(review) {
  const location = review.location == null ? "null" : `'${sqlEscape(review.location)}'`;
  return `  (
    ${review.id},
    '${sqlEscape(review.reviewerName)}',
    ${review.rating},
    '${sqlEscape(review.reviewText)}',
    ${location},
    ${review.isFeatured ? "true" : "false"},
    '${sqlEscape(review.createdAt)}'::timestamptz
  )`;
}

function buildSeedSql(reviews) {
  const rows = reviews.map(reviewToSqlRow).join(",\n");
  return `${BEGIN}
insert into public.featured_reviews (
  id,
  reviewer_name,
  rating,
  review_text,
  location,
  is_featured,
  created_at
)
values
${rows}
on conflict (id) do update set
  reviewer_name = excluded.reviewer_name,
  rating = excluded.rating,
  review_text = excluded.review_text,
  location = excluded.location,
  is_featured = excluded.is_featured,
  created_at = excluded.created_at;
${END}`;
}

function updateMigration(seedSql) {
  const migration = fs.readFileSync(migrationPath, "utf8");
  const start = migration.indexOf(BEGIN);
  const end = migration.indexOf(END);

  if (start === -1 || end === -1) {
    throw new Error(
      `Migration missing seed markers. Add:\n${BEGIN}\n...\n${END}`,
    );
  }

  const updated =
    migration.slice(0, start) +
    seedSql +
    migration.slice(end + END.length);

  fs.writeFileSync(migrationPath, updated);
}

const reviews = loadReviews();
const batch = JSON.parse(fs.readFileSync(batchPath, "utf8"));
const menu = batch[1]?.result?.data?.json;

fs.writeFileSync(extractedPath, JSON.stringify(reviews, null, 2) + "\n");
if (Array.isArray(menu)) {
  fs.writeFileSync(menuExtractedPath, JSON.stringify(menu, null, 2) + "\n");
}

const seedSql = buildSeedSql(reviews);
updateMigration(seedSql);

console.log(
  `Wrote ${reviews.length} featured reviews to ${path.relative(root, extractedPath)}`,
);
console.log(`Updated seed in ${path.relative(root, migrationPath)}`);
if (Array.isArray(menu)) {
  console.log(
    `Extracted ${menu.length} menu items to ${path.relative(root, menuExtractedPath)} (not featured_reviews).`,
  );
}

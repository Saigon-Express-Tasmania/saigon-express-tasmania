function updateMigration(seedSql) {
  const migration = fs.readFileSync(migrationPath, "utf8");
  const marker = "-- ---------------------------------------------------------------------------\n-- Seed";
  const markerIdx = migration.indexOf(marker);

  if (markerIdx === -1) {
    throw new Error("Migration missing seed section header");
  }

  const prefix = migration.slice(0, markerIdx);
  const updated = `${prefix}-- ---------------------------------------------------------------------------
-- Seed catalogue rows (regenerate: node scripts/generate-products-seed.mjs)
-- ---------------------------------------------------------------------------

${seedSql}
`;
  fs.writeFileSync(migrationPath, updated);
}

const alacarte = JSON.parse(fs.readFileSync(menuPath, "utf8"));
const wholesale = loadWholesaleProducts();
const catering = loadCateringProducts();

if (!Array.isArray(alacarte) || alacarte.length === 0) {
  throw new Error("menu.json: expected a non-empty array");
}

updateMigration(buildSeedSql(alacarte, wholesale, catering));

console.log(
  `Updated products seed: ${alacarte.length} alacarte, ${wholesale.length} wholesale, ${catering.length} catering`,
);

#!/usr/bin/env node
/**
 * Generates the public.products seed block from sample JSON files and the
 * committed catering_packs migration (catering has no JSON sample yet).
 *
 * Usage:
 *   node scripts/generate-products-seed.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const migrationPath = path.join(root, "supabase/migrations/20260528162000_products.sql");
const menuPath = path.join(root, "refs/samples/menu.json");
const wholesalePath = path.join(root, "refs/samples/wholesale-products.json");

const BEGIN = "-- BEGIN products seed (generated by scripts/generate-products-seed.mjs)";
const END = "-- END products seed";

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function sqlText(value) {
  if (value == null) return "null";
  return `'${sqlEscape(value)}'`;
}

function sqlJson(value) {
  return `'${sqlEscape(JSON.stringify(value ?? []))}'::jsonb`;
}

function sqlImageUrls(imageUrl) {
  const trimmed = imageUrl?.trim();
  if (!trimmed) return "'{}'::jsonb";
  return `'${sqlEscape(JSON.stringify({ 1920: trimmed }))}'::jsonb`;
}

function wholesaleImageUrls(item) {
  if (item.imageUrls && typeof item.imageUrls === "object" && !Array.isArray(item.imageUrls)) {
    return `'${sqlEscape(JSON.stringify(item.imageUrls))}'::jsonb`;
  }
  if (item.imageUrl?.trim()) {
    return `'${sqlEscape(JSON.stringify({ 1024: item.imageUrl.trim() }))}'::jsonb`;
  }
  return "'{}'::jsonb";
}

function inferUom(unit) {
  const u = (unit ?? "").trim().toLowerCase();
  if (u === "kg" || u.endsWith("/kg")) return "KG";
  if (u === "lbs" || u.includes("lbs")) return "LBS";
  if (u.startsWith("case")) return "CASE";
  return "EACH";
}

function inferCatchWeight(unit) {
  const u = (unit ?? "").trim().toLowerCase();
  return u === "kg" || u.endsWith("/kg") || u.includes("lbs");
}

/** Stable catalogue SKU when none is provided in source data. */
function productSku(productType, id, existingSku) {
  const trimmed = String(existingSku ?? "").trim();
  if (trimmed) return trimmed;

  const prefix =
    productType === "alacarte" ? "AL" : productType === "wholesale" ? "WH" : "CT";
  return `${prefix}-${id}`;
}

function alacarteRow(item) {
  return `  (
    ${item.id},
    'alacarte'::public.product_type,
    '${sqlEscape(item.name)}',
    '${sqlEscape(item.category)}',
    ${sqlText(item.description ?? "")},
    'EACH'::public.product_uom,
    ${item.isAvailable ? "true" : "false"},
    ${item.sortOrder ?? 0},
    ${sqlImageUrls(item.imageUrl)},
    '${sqlEscape(item.price)}',
    '',
    ${sqlText(item.wholesalePrice)},
    '[]'::jsonb,
    '',
    false,
    '{}'::bigint[],
    ${item.isPopular ? "true" : "false"},
    ${sqlJson(item.ingredients)},
    ${sqlText(productSku("alacarte", item.id, null))},
    '',
    null,
    null,
    1,
    null,
    '[]'::jsonb,
    '',
    '',
    null,
    null,
    now(),
    now()
  )`;
}

function wholesaleRow(item) {
  const uom = inferUom(item.unit);
  return `  (
    ${item.id},
    'wholesale'::public.product_type,
    ${sqlText(item.name)},
    ${sqlText(item.category)},
    ${sqlText(item.description ?? "")},
    '${uom}'::public.product_uom,
    ${item.isAvailable ? "true" : "false"},
    0,
    ${wholesaleImageUrls(item)},
    '',
    ${sqlText(item.unitPrice)},
    null,
    '[]'::jsonb,
    '',
    ${inferCatchWeight(item.unit) ? "true" : "false"},
    '{}'::bigint[],
    false,
    '[]'::jsonb,
    ${sqlText(productSku("wholesale", item.id, item.sku))},
    ${sqlText(item.unit)},
    ${item.stockQty ?? item.dailyGlobalLimit ?? 0},
    null,
    ${item.minOrderQty ?? 1},
    null,
    '[]'::jsonb,
    '',
    '',
    null,
    null,
    '${sqlEscape(item.createdAt)}'::timestamptz,
    '${sqlEscape(item.updatedAt)}'::timestamptz
  )`;
}

function cateringRow(item) {
  return `  (
    ${item.id},
    'catering'::public.product_type,
    ${sqlText(item.name)},
    ${sqlText(item.category ?? "Catering Packs")},
    ${sqlText(item.description ?? "")},
    'EACH'::public.product_uom,
    ${item.isAvailable ? "true" : "false"},
    ${item.sortOrder ?? 0},
    ${item.imageUrls ? wholesaleImageUrls({ imageUrls: item.imageUrls }) : "'{}'::jsonb"},
    ${sqlText(item.price ?? "")},
    '',
    null,
    ${sqlJson(item.prices)},
    '',
    false,
    '{}'::bigint[],
    false,
    '[]'::jsonb,
    ${sqlText(productSku("catering", item.id, null))},
    '',
    null,
    null,
    1,
    ${sqlText(item.serves)},
    ${sqlJson(item.includes)},
    ${sqlText(item.tag ?? "")},
    ${sqlText(item.tagBg ?? "")},
    ${sqlText(item.note)},
    ${sqlText(item.imageUrl)},
    now(),
    now()
  )`;
}

function loadWholesaleProducts() {
  const batch = JSON.parse(fs.readFileSync(wholesalePath, "utf8"));
  const items = batch?.[0]?.result?.data?.json;
  if (!Array.isArray(items) || items.length === 0) {
    throw new Error("wholesale-products.json: expected batch[0].result.data.json array");
  }
  return items;
}

function parseCateringTuples(sql) {
  const items = [];
  const insertBlocks = [
    ...sql.matchAll(/insert into public\.products\s*\(([\s\S]*?)\)\s*values\s*([\s\S]*?)\s*on conflict/gi),
  ];

  for (const [, columnBlock, valuesBlock] of insertBlocks) {
    const columns = columnBlock
      .split(",")
      .map((c) => c.trim())
      .filter(Boolean);

    const tupleMatches = [...valuesBlock.matchAll(/\(\s*([\s\S]*?)\s*\)(?=,\s*\(|\s*on conflict|$)/g)];

    for (const [, tupleBody] of tupleMatches) {
      const values = splitSqlTuple(tupleBody);
      const record = {};
      columns.forEach((col, idx) => {
        record[col] = parseSqlLiteral(values[idx]);
      });
      items.push({
        id: record.id,
        name: record.name,
        category: record.category,
        description: record.description,
        price: record.price,
        serves: record.serves,
        includes: record.includes ?? [],
        tag: record.tag,
        tagBg: record.tag_bg,
        note: record.note,
        prices: record.prices ?? [],
        imageUrl: record.image_url,
        imageUrls: record.image_urls ?? {},
        sortOrder: record.sort_order ?? 0,
        isAvailable: record.is_available !== false,
      });
    }
  }

  return items;
}

function splitSqlTuple(body) {
  const values = [];
  let current = "";
  let depth = 0;
  let inString = false;

  for (let i = 0; i < body.length; i += 1) {
    const ch = body[i];
    const next = body[i + 1];

    if (inString) {
      current += ch;
      if (ch === "'" && next === "'") {
        current += next;
        i += 1;
        continue;
      }
      if (ch === "'") inString = false;
      continue;
    }

    if (ch === "'") {
      inString = true;
      current += ch;
      continue;
    }

    if (ch === "[") {
      depth += 1;
      current += ch;
      continue;
    }

    if (ch === "]") {
      depth -= 1;
      current += ch;
      continue;
    }

    if (ch === "," && depth === 0) {
      values.push(current.trim());
      current = "";
      continue;
    }

    current += ch;
  }

  if (current.trim()) values.push(current.trim());
  return values;
}

function parseSqlLiteral(raw) {
  const value = raw.trim();
  if (value === "null") return null;
  if (value === "true") return true;
  if (value === "false") return false;
  if (/^-?\d+$/.test(value)) return Number(value);
  if (value.endsWith("::jsonb")) {
    const jsonText = value.slice(0, value.indexOf("::jsonb"));
    if (jsonText.startsWith("'")) {
      const inner = jsonText.slice(1, -1).replace(/''/g, "'");
      return JSON.parse(inner);
    }
  }
  if (value.startsWith("'")) {
    return value.slice(1, -1).replace(/''/g, "'");
  }
  return value;
}

function loadCateringProducts() {
  const migration = fs.readFileSync(migrationPath, "utf8");
  const cateringStart = migration.indexOf("-- Catering");
  if (cateringStart === -1) {
    throw new Error("products migration missing -- Catering section");
  }
  const cateringBlock = migration.slice(cateringStart);
  return parseCateringTuples(cateringBlock);
}


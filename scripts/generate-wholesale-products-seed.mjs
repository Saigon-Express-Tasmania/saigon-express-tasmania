#!/usr/bin/env node
/**
 * Generates the `public.wholesale_products` seed SQL block by extracting
 * wholesale products from `refs/samples/wholesale-products.json` (tRPC batch).
 *
 * Usage:
 *   node scripts/generate-wholesale-products-seed.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const batchPath = path.join(root, "refs/samples/wholesale-products.json");
const migrationPath = path.join(root, "supabase/migrations/20260527150000_wholesale_products.sql");

const BEGIN = "-- BEGIN wholesale_products seed (generated by scripts/generate-wholesale-products-seed.mjs)";
const END = "-- END wholesale_products seed";

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function sqlText(value) {
  if (value == null) return "null";
  return `'${sqlEscape(value)}'`;
}

function sqlImageUrls(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return "'{}'::jsonb";
  }
  const json = JSON.stringify(value);
  return `'${sqlEscape(json)}'::jsonb`;
}

function loadWholesaleProducts() {
  const batch = JSON.parse(fs.readFileSync(batchPath, "utf8"));
  const items = batch?.[0]?.result?.data?.json;
  if (!Array.isArray(items) || items.length === 0) {
    throw new Error("wholesale-products.json: expected a non-empty batch[0].result.data.json array");
  }
  return items;
}

function productToSqlRow(item) {
  const imageUrls =
    item.imageUrls && typeof item.imageUrls === "object" && !Array.isArray(item.imageUrls)
      ? item.imageUrls
      : item.imageUrl
        ? { "1024": item.imageUrl }
        : {};

  return `  (
    ${item.id},
    ${sqlText(item.name)},
    ${sqlText(item.sku)},
    ${sqlText(item.category)},
    ${sqlText(item.description)},
    ${sqlText(item.unit)},
    ${sqlText(item.unitPrice)},
    ${item.stockQty ?? item.dailyGlobalLimit ?? 0},
    ${item.isAvailable ? "true" : "false"},
    ${item.minOrderQty ?? 1},
    ${sqlImageUrls(imageUrls)},
    '${sqlEscape(item.createdAt)}'::timestamptz,
    '${sqlEscape(item.updatedAt)}'::timestamptz
  )`;
}

function buildSeedSql(items) {
  const rows = items.map(productToSqlRow).join(",\n");

  return `${BEGIN}
insert into public.wholesale_products (
  id,
  name,
  sku,
  category,
  description,
  unit,
  unit_price,
  daily_global_limit,
  is_available,
  min_order_qty,
  image_urls,
  created_at,
  updated_at
)
values
${rows}
on conflict (id) do update set
  name = excluded.name,
  sku = excluded.sku,
  category = excluded.category,
  description = excluded.description,
  unit = excluded.unit,
  unit_price = excluded.unit_price,
  daily_global_limit = excluded.daily_global_limit,
  is_available = excluded.is_available,
  min_order_qty = excluded.min_order_qty,
  image_urls = excluded.image_urls,
  created_at = excluded.created_at,
  updated_at = excluded.updated_at;
${END}`;
}

function updateMigration(seedSql) {
  const migration = fs.readFileSync(migrationPath, "utf8");
  const start = migration.indexOf(BEGIN);
  const end = migration.indexOf(END);

  if (start === -1 || end === -1) {
    throw new Error(`Migration missing seed markers. Add:\n${BEGIN}\n...\n${END}`);
  }

  const updated =
    migration.slice(0, start) + seedSql + "\n" + migration.slice(end + END.length);
  fs.writeFileSync(migrationPath, updated);
  console.log(`Updated seed block in ${migrationPath}`);
}

const items = loadWholesaleProducts();
updateMigration(buildSeedSql(items));

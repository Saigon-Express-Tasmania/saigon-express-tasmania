#!/usr/bin/env node
/**
 * Backfill public.menu.image_urls["1920"] from each row's image_url.
 *
 * Usage:
 *   node scripts/backfill-menu-image-urls.mjs              # write SQL only
 *   node scripts/backfill-menu-image-urls.mjs --apply        # supabase db query --linked
 *   node scripts/backfill-menu-image-urls.mjs --apply --use-service-role
 *
 * Env (for --use-service-role):
 *   SUPABASE_URL or NEXT_PUBLIC_SUPABASE_URL
 *   SUPABASE_SERVICE_ROLE_KEY
 */

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sqlOutPath = path.join(root, "refs/backfill-menu-image-urls.sql");

const apply = process.argv.includes("--apply");
const useServiceRole = process.argv.includes("--use-service-role");

const BACKFILL_SQL = `-- Generated by scripts/backfill-menu-image-urls.mjs
-- Maps image_url -> image_urls->>'1920' for all rows with a non-empty image_url.
begin;

update public.menu
set image_urls = coalesce(image_urls, '{}'::jsonb) || jsonb_build_object('1920', trim(image_url))
where image_url is not null
  and trim(image_url) <> '';

commit;
`;

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function normalizeImageUrls(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) return {};
  return Object.fromEntries(
    Object.entries(value).filter(([, url]) => String(url ?? "").trim()),
  );
}

async function applyWithServiceRole() {
  const url =
    process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    throw new Error(
      "Missing SUPABASE_URL (or NEXT_PUBLIC_SUPABASE_URL) and SUPABASE_SERVICE_ROLE_KEY",
    );
  }

  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const { data, error } = await supabase
    .from("menu")
    .select("id, image_url, image_urls");

  if (error) throw new Error(`menu select failed: ${error.message}`);

  const rows = (data ?? []).filter(
    (row) => row.image_url && String(row.image_url).trim(),
  );

  let updated = 0;
  const chunkSize = 50;

  for (let i = 0; i < rows.length; i += chunkSize) {
    const chunk = rows.slice(i, i + chunkSize);
    const results = await Promise.all(
      chunk.map((row) => {
        const image_urls = {
          ...normalizeImageUrls(row.image_urls),
          1920: String(row.image_url).trim(),
        };
        return supabase
          .from("menu")
          .update({ image_urls })
          .eq("id", row.id)
          .select("id");
      }),
    );

    for (const { data: updatedRows, error: updateError } of results) {
      if (updateError) {
        throw new Error(`menu update failed: ${updateError.message}`);
      }
      if (updatedRows?.length) updated += updatedRows.length;
    }
  }

  return { candidates: rows.length, updated };
}

function applyWithSupabaseCli(sql) {
  fs.writeFileSync(sqlOutPath, sql);
  const result = spawnSync(
    "npx",
    ["supabase@latest", "db", "query", "--linked", "-f", sqlOutPath],
    { cwd: root, stdio: "inherit", shell: true },
  );
  if (result.status !== 0) {
    throw new Error("supabase db query failed");
  }
}

loadEnvFile(path.join(root, ".env.local"));
loadEnvFile(path.join(root, ".env"));
loadEnvFile(path.join(root, "admin/.env.local"));
loadEnvFile(path.join(root, "admin/.env"));

fs.writeFileSync(sqlOutPath, BACKFILL_SQL);
console.log(`Wrote ${path.relative(root, sqlOutPath)}`);

if (!apply) {
  console.log("\nDry run. Apply with:");
  console.log("  node scripts/backfill-menu-image-urls.mjs --apply");
  console.log("  node scripts/backfill-menu-image-urls.mjs --apply --use-service-role");
  process.exit(0);
}

if (useServiceRole) {
  const { candidates, updated } = await applyWithServiceRole();
  console.log(`\nBackfill complete via service role:`);
  console.log(`  rows with image_url: ${candidates}`);
  console.log(`  updated: ${updated}`);
} else {
  applyWithSupabaseCli(BACKFILL_SQL);
  console.log("\nBackfill applied via supabase db query --linked");
}

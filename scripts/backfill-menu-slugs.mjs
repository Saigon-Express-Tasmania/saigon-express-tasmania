#!/usr/bin/env node
/**
 * Backfill public.menu.slug from name when slug is null or empty.
 *
 * Usage:
 *   node scripts/backfill-menu-slugs.mjs                    # dry run (report only)
 *   node scripts/backfill-menu-slugs.mjs --apply            # supabase db query --linked
 *   node scripts/backfill-menu-slugs.mjs --apply --use-service-role
 *
 * Env (for --use-service-role):
 *   SUPABASE_URL or NEXT_PUBLIC_SUPABASE_URL
 *   SUPABASE_SERVICE_ROLE_KEY
 */

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sqlOutPath = path.join(root, "refs/backfill-menu-slugs.sql");

const apply = process.argv.includes("--apply");
const useServiceRole = process.argv.includes("--use-service-role");

function slugFromName(name) {
  return String(name ?? "")
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function needsSlug(slug) {
  return !String(slug ?? "").trim();
}

function escapeSqlString(value) {
  return String(value).replace(/'/g, "''");
}

function buildUpdates(rows) {
  const used = new Set(
    rows
      .filter((row) => !needsSlug(row.slug))
      .map((row) => String(row.slug).trim()),
  );

  const updates = [];

  for (const row of rows) {
    if (!needsSlug(row.slug)) continue;

    let slug = slugFromName(row.name);
    if (!slug) {
      slug = `menu-item-${row.id}`;
    }
    let candidate = slug;
    if (used.has(candidate)) {
      candidate = `${slug}-${row.id}`;
    }
    used.add(candidate);
    updates.push({ id: row.id, name: row.name, slug: candidate });
  }

  return updates;
}

function buildSql(updates) {
  if (updates.length === 0) {
    return "-- No menu rows need slug backfill.\n";
  }

  const lines = [
    "-- Generated by scripts/backfill-menu-slugs.mjs",
    "begin;",
    "",
  ];

  for (const { id, slug } of updates) {
    lines.push(
      `update public.menu set slug = '${escapeSqlString(slug)}' where id = ${id};`,
    );
  }

  lines.push("", "commit;", "");
  return lines.join("\n");
}

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

async function applyWithServiceRole(updates) {
  const url =
    process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    throw new Error(
      "Missing SUPABASE_URL (or NEXT_PUBLIC_SUPABASE_URL) and SUPABASE_SERVICE_ROLE_KEY",
    );
  }

  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  let updated = 0;
  const chunkSize = 50;

  for (let i = 0; i < updates.length; i += chunkSize) {
    const chunk = updates.slice(i, i + chunkSize);
    const results = await Promise.all(
      chunk.map(({ id, slug }) =>
        supabase.from("menu").update({ slug }).eq("id", id).select("id"),
      ),
    );

    for (const { data: updatedRows, error } of results) {
      if (error) throw new Error(`menu update failed: ${error.message}`);
      if (updatedRows?.length) updated += updatedRows.length;
    }
  }

  return updated;
}

function applyWithSupabaseCli(sql) {
  fs.mkdirSync(path.dirname(sqlOutPath), { recursive: true });
  fs.writeFileSync(sqlOutPath, sql);
  const result = spawnSync(
    "npx",
    ["supabase@latest", "db", "query", "--linked", "-f", sqlOutPath],
    { cwd: root, stdio: "inherit", shell: true },
  );
  if (result.status !== 0) {
    throw new Error("supabase db query failed");
  }
}

async function fetchMenuRows() {
  const url =
    process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key =
    process.env.SUPABASE_SERVICE_ROLE_KEY ??
    process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;

  if (!url || !key) {
    throw new Error(
      "Missing Supabase credentials. Set env files or use --apply with a linked Supabase project.",
    );
  }

  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const { data, error } = await supabase
    .from("menu")
    .select("id, name, slug")
    .order("id", { ascending: true });

  if (error) throw new Error(`menu select failed: ${error.message}`);
  return data ?? [];
}

loadEnvFile(path.join(root, ".env.local"));
loadEnvFile(path.join(root, ".env"));
loadEnvFile(path.join(root, "admin/.env.local"));
loadEnvFile(path.join(root, "admin/.env"));

const rows = await fetchMenuRows();
const updates = buildUpdates(rows);
const sql = buildSql(updates);

fs.mkdirSync(path.dirname(sqlOutPath), { recursive: true });
fs.writeFileSync(sqlOutPath, sql);

console.log(`Scanned ${rows.length} menu row(s).`);
console.log(`${updates.length} row(s) need slug backfill.`);
console.log(`Wrote ${path.relative(root, sqlOutPath)}`);

if (updates.length > 0) {
  console.log("\nPreview (first 10):");
  for (const row of updates.slice(0, 10)) {
    console.log(`  id ${row.id}: "${row.name}" -> "${row.slug}"`);
  }
  if (updates.length > 10) {
    console.log(`  ... and ${updates.length - 10} more`);
  }
}

if (!apply) {
  console.log("\nDry run. Apply with:");
  console.log("  node scripts/backfill-menu-slugs.mjs --apply");
  console.log(
    "  node scripts/backfill-menu-slugs.mjs --apply --use-service-role",
  );
  process.exit(0);
}

if (useServiceRole) {
  const updated = await applyWithServiceRole(updates);
  console.log(`\nBackfill complete via service role: ${updated} updated.`);
} else {
  applyWithSupabaseCli(sql);
  console.log("\nBackfill applied via supabase db query --linked");
}

#!/usr/bin/env node
/**
 * Reads refs/samples/menu.json and updates the seed block in a given
 * supabase/migrations/*.sql file.
 *
 * Usage:
 *   node scripts/generate-menu-seed.mjs
 *   node scripts/generate-menu-seed.mjs --migrationPath supabase/migrations/2026....sql
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const menuPath = path.join(root, "refs/samples/menu.json");
const defaultMigrationPath = path.join(
  root,
  "supabase/migrations/20260526140000_menu.sql",
);

const migrationPathFlagIdx = process.argv.indexOf("--migrationPath");
const migrationPath =
  migrationPathFlagIdx !== -1 && process.argv[migrationPathFlagIdx + 1]
    ? path.isAbsolute(process.argv[migrationPathFlagIdx + 1])
      ? process.argv[migrationPathFlagIdx + 1]
      : path.join(root, process.argv[migrationPathFlagIdx + 1])
    : defaultMigrationPath;

const BEGIN = "-- BEGIN menu seed (generated by scripts/generate-menu-seed.mjs)";
const END = "-- END menu seed";

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function sqlText(value) {
  if (value == null) return "null";
  return `'${sqlEscape(value)}'`;
}

function menuToSqlRow(item) {
  const ingredients = `'${sqlEscape(JSON.stringify(item.ingredients ?? []))}'::jsonb`;
  return `  (
    ${item.id},
    '${sqlEscape(item.name)}',
    ${sqlText(item.description)},
    '${sqlEscape(item.price)}',
    ${sqlText(item.wholesalePrice)},
    '${sqlEscape(item.category)}',
    ${sqlText(item.imageUrl)},
    ${item.isAvailable ? "true" : "false"},
    ${item.isPopular ? "true" : "false"},
    ${item.sortOrder ?? 0},
    ${ingredients}
  )`;
}

function buildSeedSql(items) {
  const rows = items.map(menuToSqlRow).join(",\n");
  return `${BEGIN}
insert into public.menu (
  id,
  name,
  description,
  price,
  wholesale_price,
  category,
  image_url,
  is_available,
  is_popular,
  sort_order,
  ingredients
)
values
${rows}
on conflict (id) do update set
  name = excluded.name,
  description = excluded.description,
  price = excluded.price,
  wholesale_price = excluded.wholesale_price,
  category = excluded.category,
  image_url = excluded.image_url,
  is_available = excluded.is_available,
  is_popular = excluded.is_popular,
  sort_order = excluded.sort_order,
  ingredients = excluded.ingredients;
${END}`;
}

function updateMigration(seedSql) {
  const migration = fs.readFileSync(migrationPath, "utf8");
  const start = migration.indexOf(BEGIN);
  const end = migration.indexOf(END);

  if (start === -1 || end === -1) {
    throw new Error(`Migration missing seed markers. Add:\n${BEGIN}\n...\n${END}`);
  }

  const updated =
    migration.slice(0, start) + seedSql + migration.slice(end + END.length);

  fs.writeFileSync(migrationPath, updated);
}

const items = JSON.parse(fs.readFileSync(menuPath, "utf8"));
if (!Array.isArray(items) || items.length === 0) {
  throw new Error("menu.json: expected a non-empty array");
}

const seedSql = buildSeedSql(items);
updateMigration(seedSql);

console.log(`Updated seed with ${items.length} menu items in ${path.relative(root, migrationPath)}`);

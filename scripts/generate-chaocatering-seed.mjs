#!/usr/bin/env node
/**
 * Generate catering product + customization seeds from refs/chaocatering crawled data.
 * Writes separate SQL files (does not modify existing migrations):
 *   refs/chaocatering/generated/catering-products.sql
 *   refs/chaocatering/generated/catering-customizations.sql
 *
 * Prerequisite (for real image URLs):
 *   node scripts/upload-chaocatering-images.mjs
 *
 * Usage:
 *   node scripts/generate-chaocatering-seed.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const productsDir = path.join(root, "refs/chaocatering/data/products");
const collectionsDir = path.join(root, "refs/chaocatering/data");
const imageUrlsPath = path.join(root, "refs/chaocatering/image-urls.json");
const outDir = path.join(root, "refs/chaocatering/generated");
const productsSqlPath = path.join(outDir, "catering-products.sql");
const customizationsSqlPath = path.join(outDir, "catering-customizations.sql");

const CATERING_ID_START = 610001;
const CUSTOMIZATION_ID_START = 9;

const CATEGORY_ORDER = [
  "Saigon Top Picks",
  "Saigon Platters",
  "Individual Lunch Boxes",
  "Tea Time Boxes",
  "Funeral & Wake Catering",
  "Add-Ons",
  "Drinks & Desserts",
];

const CATERING_CUSTOM_BEGIN =
  "-- BEGIN catering customizations (generated by scripts/generate-chaocatering-seed.mjs)";
const CATERING_CUSTOM_END =
  "-- END catering customizations";

function ensureDir(dir) {
  fs.mkdirSync(dir, { recursive: true });
}

function writeSqlFile(filePath, sections) {
  const body = sections.filter(Boolean).join("\n\n");
  fs.writeFileSync(filePath, `${body}\n`);
}

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function sqlText(value) {
  if (value == null || value === "") return "''";
  return `'${sqlEscape(value)}'`;
}

function sqlNullableText(value) {
  if (value == null || value === "") return "null";
  return `'${sqlEscape(value)}'`;
}

function sqlJson(value) {
  return `'${sqlEscape(JSON.stringify(value ?? []))}'::jsonb`;
}

function sqlImageUrls(imageUrls) {
  if (!imageUrls || Object.keys(imageUrls).length === 0) return "'{}'::jsonb";
  return `'${sqlEscape(JSON.stringify(imageUrls))}'::jsonb`;
}

function slugifyKey(text, maxLen = 48) {
  const key = String(text ?? "")
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .replace(/_+/g, "_");
  const trimmed = key.slice(0, maxLen).replace(/_+$/g, "");
  return /^[a-z]/.test(trimmed) ? trimmed : `x_${trimmed}`.slice(0, maxLen);
}

function decodeHtml(text) {
  return String(text ?? "")
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function parseBodyHtml(html) {
  const raw = String(html ?? "");
  const serves = decodeHtml(
    raw.match(/<extra>([\s\S]*?)<\/extra>/i)?.[1] ??
      raw.match(/Info:\s*<\/b><\/label><extra>([\s\S]*?)<\/extra>/i)?.[1] ??
      "",
  );
  const description = decodeHtml(raw.match(/<desc>([\s\S]*?)<\/desc>/i)?.[1] ?? "");
  const includes = [...raw.matchAll(/<li>([\s\S]*?)<\/li>/gi)].map((m) =>
    decodeHtml(m[1]),
  );
  const noteLines = [];
  for (const match of raw.matchAll(/<p>([\s\S]*?)<\/p>/gi)) {
    const block = decodeHtml(match[1].replace(/<br\s*\/?>/gi, "\n"));
    for (const line of block.split("\n")) {
      const trimmed = line.replace(/^\*\s*/, "").trim();
      if (trimmed.startsWith("*")) noteLines.push(trimmed.replace(/^\*\s*/, "").trim());
      else if (trimmed) noteLines.push(trimmed);
    }
  }
  const note = noteLines.length ? noteLines.join(" ") : null;
  return { serves, description, includes, note };
}

function formatAud(amount) {
  const n = Number.parseFloat(String(amount ?? "").replace(/[^0-9.]/g, ""));
  if (!Number.isFinite(n)) return "";
  return n % 1 === 0 ? `$${n.toFixed(0)}` : `$${n.toFixed(2)}`;
}

function parseCateringUnitPrice(price) {
  const trimmed = String(price ?? "").trim();
  if (!trimmed) return "";
  const withoutPrefix = trimmed.startsWith("$") ? trimmed.slice(1) : trimmed;
  const num = Number(withoutPrefix);
  if (!Number.isFinite(num) || Number.isNaN(num)) return "";
  return String(num);
}

function meaningfulOptions(product) {
  return (product.options ?? []).filter(
    (opt) =>
      !(
        opt.name === "Title" &&
        opt.values?.length === 1 &&
        opt.values[0] === "Default Title"
      ),
  );
}

function variantPriceForValue(product, optionPosition, value) {
  const variants = (product.variants ?? []).filter(
    (v) => v.title !== "Default Title",
  );
  const field = `option${optionPosition}`;
  const allPrices = variants
    .map((v) => Number.parseFloat(v.price))
    .filter(Number.isFinite);
  const minPrice = allPrices.length ? Math.min(...allPrices) : 0;
  const matches = variants.filter((v) => v[field] === value);
  if (!matches.length) return 0;
  const prices = [...new Set(matches.map((v) => Number.parseFloat(v.price)))].filter(
    Number.isFinite,
  );
  if (prices.length !== 1) return 0;
  const delta = prices[0] - minPrice;
  return delta > 0 ? delta : 0;
}

function loadCollectionIndex() {
  const collections = {};
  const productMeta = {};

  for (const file of fs
    .readdirSync(collectionsDir)
    .filter((f) => f.endsWith(".json"))) {
    const data = JSON.parse(fs.readFileSync(path.join(collectionsDir, file), "utf8"));
    const handle = data.handle;
    const title = data.collection?.collection?.title ?? handle;
    collections[handle] = title;

    (data.products ?? []).forEach((p, index) => {
      productMeta[p.handle] = {
        category: title,
        collectionHandle: handle,
        collectionSort: CATEGORY_ORDER.indexOf(title),
        productSort: index,
      };
    });
  }

  return { collections, productMeta };
}

function loadImageUrls() {
  if (!fs.existsSync(imageUrlsPath)) return {};
  const data = JSON.parse(fs.readFileSync(imageUrlsPath, "utf8"));
  return data.products ?? {};
}

async function fetchProductFromApi(handle) {
  const res = await fetch(`https://chaocatering.com.au/products/${handle}.json`, {
    headers: { "User-Agent": "saigon-express-tasmania-seed/1.0" },
  });
  if (!res.ok) return null;
  const product = await res.json();
  return { handle, fetchedAt: new Date().toISOString(), product, localImages: {} };
}

function loadProducts(productMeta) {
  return fs
    .readdirSync(productsDir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => {
      let data = JSON.parse(fs.readFileSync(path.join(productsDir, f), "utf8"));
      const product = data.product?.product;
      if (!product) return { handle: data.handle, missing: true, meta: productMeta[data.handle] };
      const meta = productMeta[product.handle] ?? {
        category: product.product_type ?? "Catering",
        collectionSort: CATEGORY_ORDER.length,
        productSort: 0,
      };
      return { ...data, product, meta, missing: false };
    })
    .filter(Boolean);
}

async function ensureProducts(productRows, productMeta) {
  const resolved = [];
  for (const row of productRows) {
    if (!row.missing) {
      resolved.push(row);
      continue;
    }
    console.warn(`Fetching missing product JSON for ${row.handle}…`);
    const fetched = await fetchProductFromApi(row.handle);
    if (!fetched?.product?.product) {
      throw new Error(`Could not load product data for ${row.handle}`);
    }
    const outPath = path.join(productsDir, `${row.handle}.json`);
    fs.writeFileSync(outPath, JSON.stringify(fetched, null, 2));
    resolved.push({
      ...fetched,
      product: fetched.product.product,
      meta: productMeta[row.handle] ?? {
        category: fetched.product.product.product_type ?? "Catering",
        collectionSort: CATEGORY_ORDER.length,
        productSort: 0,
      },
      missing: false,
    });
  }

  return resolved
    .sort((a, b) => {
      const cat =
        (a.meta.collectionSort >= 0 ? a.meta.collectionSort : 99) -
        (b.meta.collectionSort >= 0 ? b.meta.collectionSort : 99);
      if (cat !== 0) return cat;
      if (a.meta.productSort !== b.meta.productSort) {
        return a.meta.productSort - b.meta.productSort;
      }
      return a.product.title.localeCompare(b.product.title);
    });
}

function buildCustomizations(products) {
  const groups = [];
  const productCustomizationIds = {};

  let nextId = CUSTOMIZATION_ID_START;

  for (const row of products) {
    const { product } = row;
    const opts = meaningfulOptions(product);
    const ids = [];

    for (const opt of opts) {
      const groupKey = slugifyKey(`ct_${product.handle}_${opt.position}`);
      const optionRows = (opt.values ?? []).map((value, index) => {
        const price = variantPriceForValue(product, opt.position, value);
        return {
          key: slugifyKey(value, 40),
          title: decodeHtml(value),
          price,
          sort_order: (index + 1) * 10,
        };
      });

      groups.push({
        id: nextId,
        key: groupKey,
        title: decodeHtml(opt.name),
        type: "single",
        required: true,
        sort_order: opt.position * 10,
        options: optionRows,
      });

      ids.push(nextId);
      nextId += 1;
    }

    productCustomizationIds[product.handle] = ids;
  }

  return { groups, productCustomizationIds };
}

function buildProductRow(product, id, sortOrder, imageData, sku) {
  const parsed = parseBodyHtml(product.body_html);
  const variants = product.variants ?? [];
  const defaultVariant = variants[0];
  const prices = [
    ...new Set(variants.map((v) => Number.parseFloat(v.price)).filter(Number.isFinite)),
  ];
  const price =
    prices.length > 1
      ? `From ${formatAud(Math.min(...prices))}`
      : formatAud(defaultVariant?.price ?? "");

  const image_urls = imageData?.image_urls ?? {};
  const image_url = imageData?.image_url ?? image_urls["1920"] ?? null;

  return {
    id,
    name: decodeHtml(product.title),
    category: product.meta?.category ?? product.product_type ?? "Catering",
    description: parsed.description,
    sort_order: sortOrder,
    image_urls,
    price,
    prices: [],
    sku: sku || `CT-${id}`,
    serves: parsed.serves || null,
    includes: parsed.includes,
    note: parsed.note,
    image_url,
    handle: product.handle,
  };
}

function cateringRow(item) {
  return `  (
    ${item.id},
    'catering'::public.product_type,
    ${sqlText(item.name)},
    ${sqlText(item.category)},
    ${sqlText(item.description ?? "")},
    'EACH'::public.product_uom,
    true,
    ${item.sort_order},
    ${sqlImageUrls(item.image_urls)},
    ${sqlText(item.price ?? "")},
    ${sqlText(parseCateringUnitPrice(item.price ?? ""))},
    null,
    ${sqlJson(item.prices)},
    '',
    false,
    '{}'::bigint[],
    false,
    '[]'::jsonb,
    ${sqlText(item.sku)},
    '',
    null,
    null,
    1,
    ${sqlNullableText(item.serves)},
    ${sqlJson(item.includes)},
    '',
    '',
    ${sqlNullableText(item.note)},
    ${sqlNullableText(item.image_url)},
    now(),
    now()
  )`;
}

function buildCateringProductsSql(rows) {
  const columns = `insert into public.products (
  id,
  product_type,
  name,
  category,
  description,
  uom,
  is_available,
  sort_order,
  image_urls,
  price,
  unit_price,
  wholesale_price,
  prices,
  slug,
  is_catch_weight,
  related_items,
  is_popular,
  ingredients,
  sku,
  unit,
  daily_global_limit,
  daily_customer_limit,
  min_order_qty,
  serves,
  includes,
  tag,
  tag_bg,
  note,
  image_url,
  created_at,
  updated_at
)`;

  const upsert = `on conflict (id) do update set
  product_type = excluded.product_type,
  name = excluded.name,
  category = excluded.category,
  description = excluded.description,
  uom = excluded.uom,
  is_available = excluded.is_available,
  sort_order = excluded.sort_order,
  image_urls = excluded.image_urls,
  price = excluded.price,
  unit_price = excluded.unit_price,
  wholesale_price = excluded.wholesale_price,
  prices = excluded.prices,
  slug = excluded.slug,
  is_catch_weight = excluded.is_catch_weight,
  related_items = excluded.related_items,
  is_popular = excluded.is_popular,
  ingredients = excluded.ingredients,
  sku = coalesce(nullif(trim(products.sku), ''), excluded.sku),
  unit = excluded.unit,
  daily_global_limit = excluded.daily_global_limit,
  daily_customer_limit = excluded.daily_customer_limit,
  min_order_qty = excluded.min_order_qty,
  serves = excluded.serves,
  includes = excluded.includes,
  tag = excluded.tag,
  tag_bg = excluded.tag_bg,
  note = excluded.note,
  image_url = excluded.image_url,
  updated_at = now();`;

  return `-- Catering (Chao Catering import)
${columns}
values
${rows.map(cateringRow).join(",\n")}
${upsert}`;
}

function buildCustomizationsSql(groups) {
  if (!groups.length) return "";

  const groupValues = groups
    .map(
      (g) =>
        `  (${g.id}, 'catering', '${sqlEscape(g.key)}', '${sqlEscape(g.title)}', '${g.type}', ${g.required}, ${g.sort_order})`,
    )
    .join(",\n");

  const optionValues = groups
    .flatMap((g) =>
      g.options.map(
        (opt) =>
          `  (${g.id}, '${sqlEscape(opt.key)}', '${sqlEscape(opt.title)}', ${opt.price.toFixed(2)}, ${opt.sort_order})`,
      ),
    )
    .join(",\n");

  return `${CATERING_CUSTOM_BEGIN}

insert into public.product_customizations (
  id,
  kind,
  key,
  title,
  type,
  required,
  sort_order
)
overriding system value
values
${groupValues}
on conflict (kind, key) do update set
  title = excluded.title,
  type = excluded.type,
  required = excluded.required,
  sort_order = excluded.sort_order;

insert into public.product_customization_options (
  customization_id,
  key,
  title,
  price,
  sort_order
)
values
${optionValues}
on conflict (customization_id, key) do update set
  title = excluded.title,
  price = excluded.price,
  sort_order = excluded.sort_order;

select setval(
  pg_get_serial_sequence('public.product_customizations', 'id'),
  (select coalesce(max(id), 1) from public.product_customizations)
);

${CATERING_CUSTOM_END}`;
}

function buildProductCustomizationUpdates(productRows, productCustomizationIds) {
  const lines = productRows.map((row) => {
    const ids = productCustomizationIds[row.handle] ?? [];
    const arraySql =
      ids.length > 0 ? `array[${ids.join(", ")}]::bigint[]` : `'{}'::bigint[]`;
    return `update public.products
set customization_ids = ${arraySql}
where id = ${row.id} and product_type = 'catering'::public.product_type;`;
  });

  return `-- Link catering products → customization groups
${lines.join("\n\n")}`;
}

async function main() {
  const { productMeta } = loadCollectionIndex();
  const imageUrls = loadImageUrls();
  const products = await ensureProducts(loadProducts(productMeta), productMeta);

  const productRows = products.map((row, index) => {
    const id = CATERING_ID_START + index;
    const variantSku = row.product.variants?.[0]?.sku?.trim();
    row.product.meta = row.meta;
    return buildProductRow(
      row.product,
      id,
      index,
      imageUrls[row.product.handle],
      variantSku,
    );
  });

  const { groups, productCustomizationIds } = buildCustomizations(
    products.map((row) => ({ product: { ...row.product, meta: row.meta } })),
  );

  const cateringSql = buildCateringProductsSql(productRows);
  const customizationsSql = buildCustomizationsSql(groups);
  const productUpdatesSql = buildProductCustomizationUpdates(
    productRows,
    productCustomizationIds,
  );

  ensureDir(outDir);

  writeSqlFile(productsSqlPath, [
    "-- Generated by scripts/generate-chaocatering-seed.mjs",
    `-- Generated at: ${new Date().toISOString()}`,
    cateringSql,
  ]);

  writeSqlFile(customizationsSqlPath, [
    "-- Generated by scripts/generate-chaocatering-seed.mjs",
    `-- Generated at: ${new Date().toISOString()}`,
    customizationsSql,
    productUpdatesSql,
  ]);

  const withImages = productRows.filter((r) => Object.keys(r.image_urls).length > 0).length;
  const withGallery = productRows.filter(
    (r) => Array.isArray(r.image_urls.more) && r.image_urls.more.length > 0,
  ).length;
  const galleryImages = productRows.reduce(
    (sum, row) => sum + (Array.isArray(row.image_urls.more) ? row.image_urls.more.length : 0),
    0,
  );

  console.log(`Catering products: ${productRows.length}`);
  console.log(`Customization groups: ${groups.length}`);
  console.log(`Products with images: ${withImages}/${productRows.length}`);
  console.log(`Products with gallery images: ${withGallery} (${galleryImages} extra images)`);
  if (withImages === 0) {
    console.warn(
      "No image URLs found. Run: node scripts/upload-chaocatering-images.mjs",
    );
  }
  console.log(`Wrote ${path.relative(root, productsSqlPath)}`);
  console.log(`Wrote ${path.relative(root, customizationsSqlPath)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

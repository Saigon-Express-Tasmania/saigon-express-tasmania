#!/usr/bin/env node
/**
 * Download Google reviewer avatars, upload to Supabase Storage, and emit seed SQL
 * for featured reviews.
 *
 * Usage:
 *   node scripts/upload-featured-review-avatars.mjs north-hobart
 *   node scripts/upload-featured-review-avatars.mjs hobart
 *   node scripts/upload-featured-review-avatars.mjs sorell
 *   node scripts/upload-featured-review-avatars.mjs hobart --dry-run
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const avatarsDir = path.join(root, "refs/featured-reviews/avatars");
const migrationPath = path.join(
  root,
  "supabase/migrations/20260526130000_featured_reviews.sql",
);

const BUCKET = "saigon-express-tasmania";
const FOLDER = "featured-reviews/avatars";
const REFERENCE_DATE = new Date("2026-06-28T12:00:00.000Z");

const DATASETS = {
  "north-hobart": {
    reviewsPath: path.join(root, "refs/samples/north-hobart-reviews.json"),
    urlsPath: path.join(root, "refs/featured-reviews/avatar-urls-north-hobart.json"),
    location: "North Hobart, TAS",
    startId: 7,
    begin:
      "-- BEGIN north_hobart featured_reviews seed (generated by scripts/upload-featured-review-avatars.mjs)",
    end: "-- END north_hobart featured_reviews seed",
    comment:
      "-- North Hobart Google reviews (refs/samples/north-hobart-reviews.json)",
  },
  hobart: {
    reviewsPath: path.join(root, "refs/samples/hobart-reviews.json"),
    urlsPath: path.join(root, "refs/featured-reviews/avatar-urls-hobart.json"),
    location: "Hobart, TAS",
    startId: 22,
    begin:
      "-- BEGIN hobart featured_reviews seed (generated by scripts/upload-featured-review-avatars.mjs)",
    end: "-- END hobart featured_reviews seed",
    comment: "-- Hobart Google reviews (refs/samples/hobart-reviews.json)",
  },
  sorell: {
    reviewsPath: path.join(root, "refs/samples/sorell-reviews.json"),
    urlsPath: path.join(root, "refs/featured-reviews/avatar-urls-sorell.json"),
    location: "Sorell, TAS",
    startId: 27,
    begin:
      "-- BEGIN sorell featured_reviews seed (generated by scripts/upload-featured-review-avatars.mjs)",
    end: "-- END sorell featured_reviews seed",
    comment: "-- Sorell Google reviews (refs/samples/sorell-reviews.json)",
  },
};

const args = process.argv.slice(2).filter((arg) => arg !== "--dry-run");
const datasetKey = args[0] ?? "north-hobart";
const dataset = DATASETS[datasetKey];

if (!dataset) {
  console.error(`Unknown dataset "${datasetKey}". Use: ${Object.keys(DATASETS).join(", ")}`);
  process.exit(1);
}

const dryRun = process.argv.includes("--dry-run");

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function slugify(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

const VIETNAMESE_NUMBERS = {
  một: 1,
  hai: 2,
  ba: 3,
  bốn: 4,
  bon: 4,
  năm: 5,
  nam: 5,
  sáu: 6,
  sau: 6,
  bảy: 7,
  bay: 7,
  tám: 8,
  tam: 8,
  chín: 9,
  chin: 9,
  mười: 10,
  muoi: 10,
};

function parseCount(token) {
  if (/^\d+$/.test(token)) return Number(token);
  return VIETNAMESE_NUMBERS[token] ?? null;
}

function parseReviewDate(reviewDate) {
  const normalized = reviewDate
    .replace(/^edited\s+/i, "")
    .replace(/^thời gian chỉnh sửa:\s*/i, "")
    .trim()
    .toLowerCase();

  const date = new Date(REFERENCE_DATE);

  const enWeekMatch = normalized.match(/^(\d+)\s+weeks?\s+ago$/);
  if (enWeekMatch) {
    date.setUTCDate(date.getUTCDate() - Number(enWeekMatch[1]) * 7);
    return date;
  }

  const enMonthMatch = normalized.match(/^(\d+)\s+months?\s+ago$/);
  if (enMonthMatch) {
    date.setUTCMonth(date.getUTCMonth() - Number(enMonthMatch[1]));
    return date;
  }

  const enYearMatch = normalized.match(/^(\d+)\s+years?\s+ago$/);
  if (enYearMatch) {
    date.setUTCFullYear(date.getUTCFullYear() - Number(enYearMatch[1]));
    return date;
  }

  if (normalized === "a year ago") {
    date.setUTCFullYear(date.getUTCFullYear() - 1);
    return date;
  }

  const viWeekMatch = normalized.match(/^(\d+|[a-zàáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]+)\s+tuần trước$/);
  if (viWeekMatch) {
    const count = parseCount(viWeekMatch[1]);
    if (count == null) throw new Error(`Unsupported review_date: ${reviewDate}`);
    date.setUTCDate(date.getUTCDate() - count * 7);
    return date;
  }

  const viMonthMatch = normalized.match(
    /^(\d+|[a-zàáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]+)\s+tháng trước$/,
  );
  if (viMonthMatch) {
    const count = parseCount(viMonthMatch[1]);
    if (count == null) throw new Error(`Unsupported review_date: ${reviewDate}`);
    date.setUTCMonth(date.getUTCMonth() - count);
    return date;
  }

  const viYearMatch = normalized.match(
    /^(\d+|[a-zàáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]+)\s+năm trước$/,
  );
  if (viYearMatch) {
    const count = parseCount(viYearMatch[1]);
    if (count == null) throw new Error(`Unsupported review_date: ${reviewDate}`);
    date.setUTCFullYear(date.getUTCFullYear() - count);
    return date;
  }

  throw new Error(`Unsupported review_date: ${reviewDate}`);
}

function normalizeReview(raw) {
  return {
    reviewer_name: raw.reviewer_name,
    review_date: raw.review_date,
    stars_given: raw.stars_given,
    reviewer_picture: raw.reviewer_picture ?? raw.picture_of_reviewer,
    review_content: raw.review_content ?? raw.content_of_review,
  };
}

function reviewText(review) {
  const text = review.review_content?.trim();
  if (text) return text;
  return "Left a 5-star rating on Google.";
}

function publicUrl(supabaseUrl, objectPath) {
  const base = supabaseUrl.replace(/\/$/, "");
  return `${base}/storage/v1/object/public/${BUCKET}/${objectPath}`;
}

async function downloadImage(url, destPath) {
  if (fs.existsSync(destPath)) return;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`download ${url}: ${response.status} ${response.statusText}`);
  }
  const buffer = Buffer.from(await response.arrayBuffer());
  fs.writeFileSync(destPath, buffer);
}

function detectContentType(filePath) {
  const header = fs.readFileSync(filePath).subarray(0, 4);
  if (header[0] === 0xff && header[1] === 0xd8) return "image/jpeg";
  if (header[0] === 0x89 && header[1] === 0x50) return "image/png";
  if (header.toString("ascii").startsWith("GIF8")) return "image/gif";
  return "image/jpeg";
}

async function uploadAvatar(supabase, supabaseUrl, review, slug) {
  const ext = ".jpg";
  const localPath = path.join(avatarsDir, `${slug}${ext}`);
  const objectPath = `${FOLDER}/${slug}${ext}`;

  await downloadImage(review.reviewer_picture, localPath);
  const contentType = detectContentType(localPath);

  if (!dryRun) {
    const buffer = fs.readFileSync(localPath);
    const { error } = await supabase.storage.from(BUCKET).upload(objectPath, buffer, {
      upsert: true,
      contentType,
      cacheControl: "31536000",
    });
    if (error) throw new Error(`upload ${objectPath}: ${error.message}`);
  }

  return publicUrl(supabaseUrl, objectPath);
}

function reviewToSqlRow(review, id, pictureUrl) {
  const createdAt = parseReviewDate(review.review_date).toISOString();
  return `  (
    ${id},
    '${sqlEscape(review.reviewer_name)}',
    '${sqlEscape(pictureUrl)}',
    ${Math.round(review.stars_given)},
    '${sqlEscape(reviewText(review))}',
    '${sqlEscape(dataset.location)}',
    true,
    '${createdAt}'::timestamptz
  )`;
}

function buildSeedSql(rows) {
  return `${dataset.begin}
insert into public.featured_reviews (
  id,
  reviewer_name,
  reviewer_picture,
  rating,
  review_text,
  location,
  is_featured,
  created_at
)
values
${rows.join(",\n")}
on conflict (id) do update set
  reviewer_name = excluded.reviewer_name,
  reviewer_picture = excluded.reviewer_picture,
  rating = excluded.rating,
  review_text = excluded.review_text,
  location = excluded.location,
  is_featured = excluded.is_featured,
  created_at = excluded.created_at;
${dataset.end}`;
}

function updateMigration(seedSql) {
  const migration = fs.readFileSync(migrationPath, "utf8");
  const start = migration.indexOf(dataset.begin);
  const end = migration.indexOf(dataset.end);

  const block = `\n${dataset.comment}\n${seedSql}\n`;
  const updated =
    start === -1 || end === -1
      ? migration.trimEnd() + block
      : migration.slice(0, start) +
        `${dataset.comment}\n${seedSql}` +
        migration.slice(end + dataset.end.length);

  fs.writeFileSync(migrationPath, updated.endsWith("\n") ? updated : `${updated}\n`);
}

async function main() {
  loadEnvFile(path.join(root, ".env"));
  loadEnvFile(path.join(root, ".env.local"));

  const supabaseUrl =
    process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

  if (!supabaseUrl) {
    throw new Error("Missing SUPABASE_URL or NEXT_PUBLIC_SUPABASE_URL");
  }
  if (!dryRun && !serviceKey) {
    throw new Error("Missing SUPABASE_SERVICE_ROLE_KEY (or pass --dry-run)");
  }

  const reviews = JSON.parse(fs.readFileSync(dataset.reviewsPath, "utf8")).map(
    normalizeReview,
  );
  fs.mkdirSync(avatarsDir, { recursive: true });

  const supabase = serviceKey
    ? createClient(supabaseUrl, serviceKey, {
        auth: { persistSession: false, autoRefreshToken: false },
      })
    : null;

  const avatarUrls = {};
  const sqlRows = [];

  for (let index = 0; index < reviews.length; index += 1) {
    const review = reviews[index];
    const id = dataset.startId + index;
    const slug = slugify(review.reviewer_name);
    const pictureUrl = await uploadAvatar(supabase, supabaseUrl, review, slug);
    avatarUrls[slug] = pictureUrl;
    sqlRows.push(reviewToSqlRow(review, id, pictureUrl));
    console.log(`→ ${review.reviewer_name} (id ${id})`);
  }

  fs.writeFileSync(
    dataset.urlsPath,
    JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        dataset: datasetKey,
        bucket: BUCKET,
        folder: FOLDER,
        location: dataset.location,
        dryRun,
        avatars: avatarUrls,
      },
      null,
      2,
    ) + "\n",
  );

  const seedSql = buildSeedSql(sqlRows);
  updateMigration(seedSql);

  console.log(`\nWrote ${path.relative(root, dataset.urlsPath)}`);
  console.log(`Updated ${path.relative(root, migrationPath)}`);
  console.log(
    `Inserted ${reviews.length} ${dataset.location} reviews (ids ${dataset.startId}-${dataset.startId + reviews.length - 1})`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});

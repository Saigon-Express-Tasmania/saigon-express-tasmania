#!/usr/bin/env node
/**
 * Sync image_url from refs/samples/menu.json and refs/samples/promotions.json
 * into the linked Supabase project (public.menu, public.promotions).
 *
 * Usage:
 *   node scripts/sync-image-urls-to-supabase.mjs              # write SQL only
 *   node scripts/sync-image-urls-to-supabase.mjs --apply      # run via supabase db query --linked
 *   node scripts/sync-image-urls-to-supabase.mjs --apply --use-service-role
 *
 * Env (optional, for --use-service-role):
 *   SUPABASE_URL or NEXT_PUBLIC_SUPABASE_URL
 *   SUPABASE_SERVICE_ROLE_KEY
 */

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { createClient } from "@supabase/supabase-js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const menuPath = path.join(root, "refs/samples/menu.json");
const promotionsPath = path.join(root, "refs/samples/promotions.json");
const sqlOutPath = path.join(root, "refs/sync-image-urls.sql");

const apply = process.argv.includes("--apply");
const useServiceRole = process.argv.includes("--use-service-role");

function loadEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return;
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
}

function sqlEscape(value) {
  return String(value).replace(/'/g, "''");
}

function loadMenuItems() {
  const items = JSON.parse(fs.readFileSync(menuPath, "utf8"));
  if (!Array.isArray(items)) {
    throw new Error("menu.json: expected a top-level array");
  }
  return items
    .filter((item) => item?.id != null && item.imageUrl)
    .map((item) => ({ id: item.id, imageUrl: item.imageUrl }));
}

function loadPromotions() {
  const raw = JSON.parse(fs.readFileSync(promotionsPath, "utf8"));
  const list = Array.isArray(raw)
    ? raw[0]?.result?.data?.json ?? raw
    : raw?.result?.data?.json ?? raw;
  if (!Array.isArray(list)) {
    throw new Error("promotions.json: could not find promotions array");
  }
  return list
    .filter((item) => item?.id != null && item.imageUrl)
    .map((item) => ({ id: item.id, imageUrl: item.imageUrl }));
}

function buildUpdateSql(table, rows) {
  if (rows.length === 0) return `-- No ${table} rows with imageUrl\n`;
  const lines = rows.map(
    (row) =>
      `update public.${table}\nset image_url = '${sqlEscape(row.imageUrl)}'\nwhere id = ${row.id};`,
  );
  return `-- ${table}: ${rows.length} row(s)\n${lines.join("\n\n")}\n`;
}

function buildSql(menuRows, promotionRows) {
  return [
    "-- Generated by scripts/sync-image-urls-to-supabase.mjs",
    "begin;",
    "",
    buildUpdateSql("menu", menuRows),
    buildUpdateSql("promotions", promotionRows),
    "commit;",
    "",
  ].join("\n");
}

async function applyWithServiceRole(menuRows, promotionRows) {
  const url =
    process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    throw new Error(
      "Missing SUPABASE_URL (or NEXT_PUBLIC_SUPABASE_URL) and SUPABASE_SERVICE_ROLE_KEY",
    );
  }

  const supabase = createClient(url, key, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const chunkSize = 50;
  let menuUpdated = 0;
  let promotionsUpdated = 0;

  for (let i = 0; i < menuRows.length; i += chunkSize) {
    const chunk = menuRows.slice(i, i + chunkSize);
    const results = await Promise.all(
      chunk.map((row) =>
        supabase
          .from("menu")
          .update({ image_url: row.imageUrl })
          .eq("id", row.id)
          .select("id"),
      ),
    );
    for (const { data, error } of results) {
      if (error) throw new Error(`menu update failed: ${error.message}`);
      if (data?.length) menuUpdated += data.length;
    }
  }

  for (let i = 0; i < promotionRows.length; i += chunkSize) {
    const chunk = promotionRows.slice(i, i + chunkSize);
    const results = await Promise.all(
      chunk.map((row) =>
        supabase
          .from("promotions")
          .update({ image_url: row.imageUrl })
          .eq("id", row.id)
          .select("id"),
      ),
    );
    for (const { data, error } of results) {
      if (error) throw new Error(`promotions update failed: ${error.message}`);
      if (data?.length) promotionsUpdated += data.length;
    }
  }

  return { menuUpdated, promotionsUpdated };
}

function applyWithSupabaseCli(sql) {
  fs.writeFileSync(sqlOutPath, sql);
  const result = spawnSync(
    "npx",
    ["supabase@latest", "db", "query", "--linked", "-f", sqlOutPath],
    { cwd: root, stdio: "inherit", shell: true },
  );
  if (result.status !== 0) {
    throw new Error("supabase db query failed");
  }
}

loadEnvFile(path.join(root, ".env.local"));
loadEnvFile(path.join(root, ".env"));

const menuRows = loadMenuItems();
const promotionRows = loadPromotions();
const sql = buildSql(menuRows, promotionRows);

fs.writeFileSync(sqlOutPath, sql);
console.log(`Wrote ${path.relative(root, sqlOutPath)}`);
console.log(`  menu: ${menuRows.length} update(s)`);
console.log(`  promotions: ${promotionRows.length} update(s)`);

if (!apply) {
  console.log("\nDry run. Apply with:");
  console.log("  node scripts/sync-image-urls-to-supabase.mjs --apply");
  process.exit(0);
}

if (useServiceRole) {
  const { menuUpdated, promotionsUpdated } = await applyWithServiceRole(
    menuRows,
    promotionRows,
  );
  console.log(`\nUpdated via service role:`);
  console.log(`  menu: ${menuUpdated} row(s)`);
  console.log(`  promotions: ${promotionsUpdated} row(s)`);
} else {
  applyWithSupabaseCli(sql);
  console.log("\nApplied via supabase db query --linked");
}
